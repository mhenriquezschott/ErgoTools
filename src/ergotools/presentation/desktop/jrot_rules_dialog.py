        """Build a compact entity title and plain-language scope explanation.

        Args:
            None.

        Returns:
            Owned themed heading; captions explain local restrictions without
            implying that this dialog runs an optimization or saves project data.
        """
        frame = QFrame(self)
        frame.setObjectName("restrictionHeading")
        frame.setStyleSheet(
            "QFrame#restrictionHeading {background:white;border:1px solid #D5DEE5;"
            "border-radius:6px;}"
        )
        row = QHBoxLayout(frame)
        row.setContentsMargins(12, 10, 12, 10)
        row.setSpacing(12)
        icon = QLabel()
        icon.setPixmap(self.icons.get("worker_restrictions", QIcon()).pixmap(44, 44))
        row.addWidget(icon, 0, Qt.AlignmentFlag.AlignTop)
        text = QVBoxLayout()
        text.setSpacing(4)
        self.title = QLabel(self.windowTitle())
        self.title.setStyleSheet("font-size:20px;font-weight:700;color:#0B326C;")
        text.addWidget(self.title)
        explanation = QLabel(
            self.text(
                "Keep workers on a fixed Job, exclude Jobs they cannot perform, "
                "or prevent consecutive High-risk Jobs.",
                "Fije un trabajo para cada trabajador, excluya trabajos que no "
                "pueda realizar o evite trabajos consecutivos de riesgo alto.",
            )
        )
        explanation.setWordWrap(True)
        text.addWidget(explanation)
        scope = QLabel(
            self.text(
                "Rules apply to the selected Jobs and workplaces. High means "
                "High in any analyzed tool; breaks do not reset the sequence.",
                "Las reglas usan los trabajos y lugares seleccionados. Alto "
                "significa alto en cualquier herramienta analizada; los "
                "descansos no reinician la secuencia.",
            )
        )
