    def build_summary(self) -> QFrame:
        """Create live draft counts and one visible place for guidance and warnings.

        Args:
            None.

        Returns:
            Owned summary panel. Counters describe current draft choices, not
            solver feasibility; missing neighbor context remains an explicit warning.
        """
        frame = QFrame(self)
        frame.setObjectName("restrictionSummary")
        frame.setStyleSheet(
            "QFrame#restrictionSummary {background:white;border:1px solid #D5DEE5;"
            "border-radius:6px;}"
        )
        layout = QVBoxLayout(frame)
        layout.setContentsMargins(10, 8, 10, 8)
        layout.setSpacing(6)
        title = QLabel(self.text("Restriction summary", "Resumen de restricciones"))
        title.setStyleSheet("font-weight:700;color:#0B326C;")
        layout.addWidget(title)
        counts = QHBoxLayout()
        counts.setSpacing(8)
        self.summary_counts: dict[str, QLabel] = {}
        for key in ("workers", "fixed", "excluded", "high"):
            label = QLabel()
            label.setStyleSheet(
                "background:#EAF3F7;color:#0B326C;border-radius:4px;padding:5px 8px;"
            )
            self.summary_counts[key] = label
            counts.addWidget(label, 1)
        layout.addLayout(counts)
        self.summary_status = QLabel()
        self.summary_status.setWordWrap(True)
        layout.addWidget(self.summary_status)
        self.guidance = QLabel()
        self.guidance.setWordWrap(True)
        self.guidance.setStyleSheet(
            "background:#FFF3D6;color:#805000;padding:7px;font-weight:bold;"
        )
        self.guidance.hide()
        layout.addWidget(self.guidance)
        return frame

    def update_summary(self) -> None:
        """Project draft counts and unresolved requested neighboring-shift context.

        Args:
            None.

        Returns:
            None; updates presentation only. It neither accepts rules nor asserts
            feasibility, result freshness or successful optimization.
        """
        fixed = sum(c[0].currentData() is not None for c in self.controls.values())
        excluded = sum(len(keys) for keys in self.excluded.values())
        high = sum(c[2].isChecked() for c in self.controls.values())
        values = {
            "workers": (len(self.controls), self.text("Workers", "Trabajadores")),
            "fixed": (fixed, self.text("Fixed Jobs", "Trabajos fijos")),
            "excluded": (
                excluded,
                self.text("Job exclusions", "Exclusiones de trabajos"),
            ),
            "high": (high, self.text("No adjacent High", "Sin alto consecutivo")),
        }
        for key, (count, caption) in values.items():
            self.summary_counts[key].setText(f"<b>{count}</b> · {caption}")
        missing_previous = self.inputs.previous is None and any(
            c[2].isChecked() and c[3].isChecked() for c in self.controls.values()
        )
        missing_following = self.inputs.following is None and any(
            c[2].isChecked() and c[4].isChecked() for c in self.controls.values()
        )
        if missing_previous or missing_following:
            missing = []
            if missing_previous:
                missing.append(self.text("previous", "anterior"))
            if missing_following:
                missing.append(self.text("following", "siguiente"))
            self.summary_status.setText(
                self.text(
                    "Neighboring shift results needed: "
                    + ", ".join(missing)
                    + ". Select them in step 03 before optimizing.",
                    "Faltan resultados de turnos vecinos: "
                    + ", ".join(missing)
                    + ". Selecciónelos en el paso 03 antes de optimizar.",
                )
            )
            self.summary_status.setStyleSheet(
                "background:#FFF3D6;color:#805000;border-radius:4px;padding:5px 8px;"
            )
        else:
            self.summary_status.setText(
                self.text(
                    "No restrictions selected. Workers may perform any selected Job."
                    if not fixed and not excluded and not high
                    else "Use restrictions applies this draft to the rotation; "
                    "Cancel keeps the previous restrictions. The optimizer checks "
                    "the complete schedule.",
                    "Sin restricciones seleccionadas. Los trabajadores pueden "
                    "realizar cualquier trabajo seleccionado."
                    if not fixed and not excluded and not high
                    else "Usar restricciones aplica este borrador a la rotación; "
                    "Cancelar conserva las restricciones anteriores. El optimizador "
                    "comprueba el horario completo.",
                )
            )
            self.summary_status.setStyleSheet("color:#4E6578;")

    def bulk_checks(self, column: int, checked: bool) -> None:
        """Set a checkbox column for eligible workers in this local draft only.

        Args:
            column: Logical checkbox column3/4/5, mapped to its row control.
            checked: True selects enabled rows; False clears every row.

        Returns:
            None; boundary selections require No adjacent High. Clearing High also
            clears its boundary flags. Use restrictions still owns project acceptance.
        """
        for controls in self.controls.values():
            control = controls[column - 1]
            assert isinstance(control, QCheckBox)
            if not checked or control.isEnabled():
                control.setChecked(checked)
            if column == 3 and not checked:
                controls[3].setChecked(False)
                controls[4].setChecked(False)
        self.update_bulk_state()

    def update_bulk_state(self) -> None:
        """Enable boundary All actions only when some worker has adjacency enabled.

        Args:
            None.

        Returns:
            None; disabled buttons explain the prerequisite and change no flags.
        """
        active = any(c[2].isChecked() for c in self.controls.values())
        for column in (4, 5):
            button = self.column_header.buttons[column][0]
            button.setEnabled(active)
            button.setToolTip(
                self.text(
                    "Select all workers with No adjacent High enabled"
                    if active
                    else "Enable No adjacent High first",
                    "Seleccionar trabajadores con Sin alto consecutivo"
                    if active
                    else "Active Sin alto consecutivo primero",
                )
            )
        self.column_header.position_actions()
        self.update_summary()

    def clear_fixed(self) -> None:
        """Remove all fixed Jobs without changing exclusions or checkbox rules.

        Args:
            None.

        Returns:
            None; removing constraints remains a local draft edit until acceptance.
        """
        for worker, controls in self.controls.items():
            with QSignalBlocker(controls[0]):
                controls[0].setCurrentIndex(0)
            self._fixed_keys[worker] = None
        self.refresh_fixed_choices()

    def clear_excluded(self) -> None:
        """Remove all local excluded sets and immediately refresh their visible names.

        Args:
            None.

        Returns:
            None; no saved Job, worker or rule is removed by this local action.
        """
        for worker in self.controls:
            self.excluded[worker].clear()
            self.update_exclusion_label(worker)
        self.refresh_fixed_choices()

    def text(self, english: str, spanish: str) -> str:
        """Resolve owned captions while retaining literal identities.

        Args:
            english: English interface text.
            spanish: Spanish interface text.

        Returns:
            Current language caption.
        """
        return spanish if self.language is Language.SPANISH else english

    def update_exclusion_label(self, worker: str) -> None:
        """Project the local exclusion count and exact selected names.

        Args:
            worker: Existing row identity.

        Returns:
            None; no rule is accepted into project data here.
        """
        button = self.controls[worker][1]
        keys = sorted(self.excluded[worker])
        captions = [self.labels[k] for k in keys]
        summary = self.exclusion_summaries[worker]
        summary.setText(
            "\n".join(captions[:2])
            + (self.text("\n+ ", "\n+ ") + str(len(keys) - 2) if len(keys) > 2 else "")
            if keys
            else self.text("No excluded Jobs", "Sin trabajos excluidos")
        )
        summary.setToolTip("\n".join(captions))
        button.setText(self.text("Edit…", "Editar…"))
        button.setToolTip(
            "\n".join(self.labels[k] for k in sorted(self.excluded[worker]))
            or self.text(
                "Choose Jobs this worker cannot perform. Cancel keeps existing "
                "exclusions.",
                "Elija los trabajos que no puede realizar. Cancelar conserva las "
                "exclusiones existentes.",
            )
        )

    def choose_exclusions(self, worker: str) -> None:
        """Reuse the checked real-position picker for a row's local excluded set.

        Args:
            worker: Existing selected participant.

        Returns:
            None; cancellation retains the prior local checks.
        """
        targets = {t.key: t.job_id for t in self.inputs.targets}
        choices = tuple(
            JrotCatalogChoice(k, (targets[k], v))
            for k, v in self.labels.items()
            if k != self.controls[worker][0].currentData()
        )
        dialog = JrotCatalogPicker(
            self.text("Excluded Jobs", "Trabajos excluidos"),
            ("Job ID", self.text("Job / workplace", "Trabajo / lugar")),
            choices,
            tuple(self.excluded[worker]),
            self.language,
            self,
            icons=self.icons,
            entity_icon="job_management",
        )
        try:
            if dialog.exec() == QDialog.Accepted:
                offered = {choice.key for choice in choices}
                candidate = set(dialog.selected) & offered
                previous = self.excluded[worker]
                self.excluded[worker] = candidate
                try:
                    allowed_positions(replace(self.inputs, rules=self.collect_rules()))
                except ValueError:
                    self.excluded[worker] = previous
                    QMessageBox.warning(
                        self,
                        self.text(
                            "Jobs must remain available",
                            "Deben quedar trabajos disponibles",
                        ),
                        self.text(
                            "These exclusions prevent a valid assignment. "
                            "Keep a feasible Job for every worker. "
                            "Previous exclusions are unchanged.",
                            "Las exclusiones impiden una asignación válida. "
                            "Debe quedar un trabajo factible para cada uno. "
                            "Se conservan las exclusiones anteriores.",
                        ),
                    )
                    return
                self.update_exclusion_label(worker)
                self.refresh_fixed_choices()
        finally:
            dialog.deleteLater()

    def accept_rules(self) -> None:
        """Reject contradictory static staffing before returning one immutable rule set.

        Args:
            None.

        Returns:
            None; missing requested neighbors remain visibly unresolved until
            selected.
        """
        rules = self.collect_rules()
        try:
            allowed_positions(replace(self.inputs, rules=rules))
        except ValueError as error:
            QMessageBox.warning(
                self,
                self.text("Invalid restrictions", "Restricciones inválidas"),
                str(error),
            )
            return
        self.selected = rules
        self.accept()

    def collect_rules(self) -> tuple[RotationRule, ...]:
        """Read the local draft consistently for live and final feasibility validation.

        Args:
            None.

        Returns:
            Exact typed rules without accepting any project change.
        """
        rules: list[RotationRule] = []
        for worker, (
            fixed,
            _excluded,
            high,
            previous,
            following,
        ) in self.controls.items():
            if fixed.currentData() is not None:
                rules.append(FixedPosition(worker, str(fixed.currentData())))
            rules.extend(
                ExcludedPosition(worker, key) for key in sorted(self.excluded[worker])
            )
            if high.isChecked():
                rules.append(
                    NoAdjacentHigh(worker, previous.isChecked(), following.isChecked())
                )
        return tuple(rules)

    def refresh_fixed_choices(self) -> None:
        """Disable excluded or already-fixed Jobs without silently changing draft rules.

        Args:
            None.

        Returns:
            None; existing exact Job/placement identities and selected indices survive.
        """
        fixed_keys = {
            worker: controls[0].currentData()
            for worker, controls in self.controls.items()
        }
        for worker, controls in self.controls.items():
            combo = controls[0]
            model = combo.model()
            assert isinstance(model, QStandardItemModel)
            with QSignalBlocker(combo):
                for index in range(1, combo.count()):
                    key = combo.itemData(index)
                    excluded = key in self.excluded[worker]
                    occupied = any(
                        other != worker and target == key
                        for other, target in fixed_keys.items()
                    )
                    item = model.item(index)
                    assert item is not None
                    item.setEnabled(not excluded and not occupied)
                    item.setToolTip(
                        self.text(
                            "Excluded for this worker"
                            if excluded
                            else "Already fixed to another worker"
                            if occupied
                            else "Keep this worker on this Job in every work block",
                            "Excluido para este trabajador"
                            if excluded
                            else "Ya fijado para otro trabajador"
                            if occupied
                            else "Mantener este trabajo en todos los bloques",
                        )
                    )

        self.update_summary()

    def fixed_changed(self, worker: str, _index: int) -> None:
        """Reject a fixed Job that prevents complete static staffing before staging it.

        Args:
            worker: Exact participant whose local combo changed.
            _index: Native display index; the Job identity comes from item data.

        Returns:
            None; invalid choices restore the prior selection with visible guidance.
        """
        combo = self.controls[worker][0]
        try:
            allowed_positions(replace(self.inputs, rules=self.collect_rules()))
        except ValueError:
            with QSignalBlocker(combo):
                combo.setCurrentIndex(max(0, combo.findData(self._fixed_keys[worker])))
            self.guidance.setText(
                self.text(
                    "This fixed Job would leave no valid assignment for all workers. "
                    "Choose another Job or revise the exclusions. "
                    "The previous choice is kept.",
                    "Este trabajo fijo impide una asignación válida para todos. "
                    "Elija otro o revise las exclusiones. "
                    "Se conserva la selección anterior.",
                )
            )
            self.guidance.show()
        else:
            self._fixed_keys[worker] = combo.currentData()
            self.guidance.clear()
            self.guidance.hide()
        self.refresh_fixed_choices()
