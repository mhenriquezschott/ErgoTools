from ergotools.presentation.desktop.theme.dialogs import apply_dialog_theme
from ergotools.presentation.desktop.workflow_action_style import set_action_icon


class JrotRulesDialog(QDialog):
    """Prepare typed per-worker restrictions without an independent document/history."""

    def __init__(
        self,
        inputs: RotationInputs,
        labels: Mapping[str, str],
        icons: Mapping[str, QIcon],
        language: Language,
        parent: QWidget,
        *,
        worker_labels: Mapping[str, str] | None = None,
    ) -> None:
        """Edit exact worker and position rules in a local proposal.

        Args:
            inputs: Current selected participants/positions and existing
            restrictions.
            labels: Human-readable position names, keyed by exact opaque identity.
            icons: Current packaged entity icons for the reusable exclusion picker.
            language: Owned interface captions.
            parent: Guided project owner.
            worker_labels: Optional full ID/name captions; rules continue to use IDs.

        Returns:
            None; Cancel preserves the complete current project state.
        """
        super().__init__(parent)
        self.inputs, self.labels, self.icons, self.language = (
            inputs,
            labels,
            icons,
            language,
        )
        self.selected = inputs.rules
        self._fixed_keys: dict[str, object] = {}
        self.excluded = {
            w.worker_id: {
                r.target_key
                for r in inputs.rules
                if isinstance(r, ExcludedPosition) and r.worker_id == w.worker_id
            }
            for w in inputs.workers
        }
        self.exclusion_summaries: dict[str, QLabel] = {}
        self.controls: dict[
            str, tuple[QComboBox, QPushButton, QCheckBox, QCheckBox, QCheckBox]
        ] = {}
        self.setWindowTitle(
            self.text("Worker restrictions", "Restricciones de trabajadores")
        )
        self.resize(1240, 660)
        apply_dialog_theme(self)
        layout = QVBoxLayout(self)
        layout.setSpacing(8)
        layout.addWidget(self.build_heading())
        summary_panel = self.build_summary()
        self.table = QTableWidget(len(inputs.workers), 6)
        style_rotation_table(self.table)
        self.table.setHorizontalHeaderLabels(
            [
                self.text("Worker", "Trabajador"),
                self.text("Fixed Job", "Trabajo fijo"),
                self.text("Excluded Jobs", "Trabajos excluidos"),
                self.text("No adjacent High", "Sin alto consecutivo"),
                self.text("Previous boundary", "Límite anterior"),
                self.text("Following boundary", "Límite siguiente"),
            ]
        )
        self.table.setIconSize(QSize(26, 26))
        for column, name in (
            (0, "worker"),
            (1, "fixed_job"),
            (2, "excluded_jobs"),
            (3, "no_adjacent_high"),
            (4, "previous_rotation_result"),
            (5, "following_rotation_result"),
        ):
            header = self.table.horizontalHeaderItem(column)
            if header is not None:
                header.setIcon(self.icons.get(name, QIcon()))
        for row, w in enumerate(inputs.workers):
            caption = (worker_labels or {}).get(w.worker_id, w.worker_id)
            item = QTableWidgetItem(caption)
            item.setToolTip(caption)
            item.setFlags(Qt.ItemFlags(Qt.ItemFlag.ItemIsEnabled))
            self.table.setItem(row, 0, item)
            fixed = QComboBox()
            fixed.addItem(self.text("Not fixed", "Sin fijar"), None)
            for key, label in labels.items():
                fixed.addItem(label, key)
            fixed_rule = next(
                (
                    r
                    for r in inputs.rules
                    if isinstance(r, FixedPosition) and r.worker_id == w.worker_id
                ),
                None,
            )
            fixed.setCurrentIndex(
                max(0, fixed.findData(fixed_rule.target_key if fixed_rule else None))
            )
            excluded = QPushButton(self.text("Edit…", "Editar…"))
            excluded.setIcon(self.icons.get("excluded_jobs", QIcon()))
            excluded.setIconSize(QSize(28, 28))
            excluded.setMinimumWidth(110)
            excluded.setAutoDefault(False)
            excluded.clicked.connect(partial(self.choose_exclusions, w.worker_id))
            high = QCheckBox()
            previous = QCheckBox()
            following = QCheckBox()
            rule = next(
                (
                    r
                    for r in inputs.rules
                    if isinstance(r, NoAdjacentHigh) and r.worker_id == w.worker_id
                ),
                None,
            )
            high.setChecked(rule is not None)
            previous.setChecked(rule.previous if rule else False)
            following.setChecked(rule.following if rule else False)
            previous.setEnabled(high.isChecked())
            following.setEnabled(high.isChecked())
            high.toggled.connect(previous.setEnabled)
            high.toggled.connect(following.setEnabled)
            self.controls[w.worker_id] = (fixed, excluded, high, previous, following)
            for col, control in enumerate(self.controls[w.worker_id], 1):
                if isinstance(control, QCheckBox):
                    host = QWidget()
                    centered = QHBoxLayout(host)
                    centered.setContentsMargins(0, 0, 0, 0)
                    centered.setAlignment(Qt.AlignmentFlag.AlignCenter)
                    centered.addWidget(control)
                    self.table.setCellWidget(row, col, host)
                elif col == 2:
                    host = QWidget()
                    row_layout = QHBoxLayout(host)
                    row_layout.setContentsMargins(6, 2, 6, 2)
                    summary = QLabel()
                    summary.setWordWrap(True)
                    self.exclusion_summaries[w.worker_id] = summary
                    row_layout.addWidget(summary, 1)
                    row_layout.addWidget(control)
                    self.table.setCellWidget(row, col, host)
                else:
                    self.table.setCellWidget(row, col, control)
            fixed.setToolTip(
                self.text(
                    "Keep this worker at the selected Job for every block.",
                    "Mantener al trabajador en el trabajo seleccionado durante "
                    "todos los bloques.",
                )
            )
            high.setToolTip(
                self.text(
                    "Prevent consecutive High-risk Jobs within this shift.",
                    "Impedir trabajos consecutivos de riesgo alto dentro de este "
                    "turno.",
                )
            )
            previous.setToolTip(
                self.text(
                    "Also check the linked previous shift's last block. Choose "
                    "that rotation in step 03.",
                    "Comprobar también el último bloque del turno anterior "
                    "vinculado. Elija esa rotación en el paso 03.",
                )
            )
            following.setToolTip(
                self.text(
                    "Also check the linked following shift's first block. Choose "
                    "that rotation in step 03.",
                    "Comprobar también el primer bloque del turno siguiente "
                    "vinculado. Elija esa rotación en el paso 03.",
                )
            )
            self._fixed_keys[w.worker_id] = fixed.currentData()
            fixed.currentIndexChanged.connect(partial(self.fixed_changed, w.worker_id))
            self.update_exclusion_label(w.worker_id)
        actions_by_column: dict[
            int, tuple[tuple[str, str, Callable[[], None]], ...]
        ] = {
            1: (
                (
                    self.text("Clear all", "Quitar todos"),
                    self.text(
                        "Remove every fixed Job in this draft",
                        "Quitar todos los trabajos fijos del borrador",
                    ),
                    self.clear_fixed,
                ),
            ),
            2: (
                (
                    self.text("Clear all", "Quitar todos"),
                    self.text(
                        "Remove all excluded Jobs in this draft",
                        "Quitar todas las exclusiones del borrador",
                    ),
                    self.clear_excluded,
                ),
            ),
        }
        for column in (3, 4, 5):
            actions_by_column[column] = (
                (
                    self.text("All", "Todos"),
                    self.text(
                        "Select all eligible workers in this column",
                        "Seleccionar todos los trabajadores habilitados",
                    ),
                    partial(self.bulk_checks, column, True),
                ),
                (
                    self.text("None", "Ninguno"),
                    self.text(
                        "Clear this option for all workers",
                        "Quitar esta opción para todos los trabajadores",
                    ),
                    partial(self.bulk_checks, column, False),
                ),
            )
        self.column_header = ColumnActionHeader(self.table, actions_by_column)
        self.column_header.setIconSize(QSize(28, 28))
        self.table.setHorizontalHeader(self.column_header)
        style_rotation_table(self.table)
        scrollbar = self.table.horizontalScrollBar()
        assert scrollbar is not None
        scrollbar.valueChanged.connect(self.column_header.position_actions)
        for controls in self.controls.values():
            controls[2].toggled.connect(self.update_bulk_state)
            controls[3].toggled.connect(self.update_summary)
            controls[4].toggled.connect(self.update_summary)
        self.update_bulk_state()
        self.refresh_fixed_choices()
        self.table.resizeColumnsToContents()
        header = self.table.horizontalHeader()
        assert header is not None
        header.setStretchLastSection(False)
        header.setSectionResizeMode(QHeaderView.ResizeToContents)
        for column in (1, 2):
            header.setSectionResizeMode(column, QHeaderView.Stretch)
        header.setMinimumSectionSize(90)
        for row in range(self.table.rowCount()):
            self.table.setRowHeight(row, 64)
        layout.addWidget(self.table, 1)
        layout.addWidget(summary_panel)
        actions = QHBoxLayout()
        actions.addStretch(1)
        for label, callback in [
            (self.text("Cancel", "Cancelar"), self.reject),
            (self.text("Use restrictions", "Usar restricciones"), self.accept_rules),
        ]:
            button = QPushButton(label)
            set_action_icon(
                button,
                self.icons["cancel" if callback == self.reject else "filter_apply"],
            )
            button.setAutoDefault(False)
            button.clicked.connect(callback)
            actions.addWidget(button)
        layout.addLayout(actions)

