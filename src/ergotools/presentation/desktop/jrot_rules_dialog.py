from dataclasses import replace
from functools import partial

from PyQt5.QtCore import QSignalBlocker, QSize, Qt
from PyQt5.QtGui import QIcon, QStandardItemModel
from PyQt5.QtWidgets import (
    QCheckBox,
    QComboBox,
    QDialog,
    QFrame,
    QHBoxLayout,
    QHeaderView,
    QLabel,
    QMessageBox,
    QPushButton,
    QTableWidget,
    QTableWidgetItem,
    QVBoxLayout,
    QWidget,
)

from ergotools.domain.language import Language
from ergotools.domain.rotation_constraints import (
    ExcludedPosition,
    FixedPosition,
    NoAdjacentHigh,
    RotationRule,
)
from ergotools.domain.rotation_planning import allowed_positions
from ergotools.domain.rotation_scenario import RotationInputs
from ergotools.presentation.desktop.column_action_header import ColumnActionHeader
